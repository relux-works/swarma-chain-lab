#!/usr/bin/env python3
"""Fail when any internal require edge is older than the published snapshot.

Every go.mod in the checkout is parsed by Go itself (`go mod edit -json`), so
standalone `require x v` lines, `require ( ... )` blocks and `// indirect`
entries are all the same edge. Never replace this with a line or whitespace
filter: that class of parser missed two standalone requires (PR 72, F1).

Exit status: 0 clean, 1 violations, 2 usage or tool failure.
"""
import argparse
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import sys

REPO_MODULE = "github.com/relux-works/swarma-chain-lab"
DOC_BEGIN = "<!-- module-graph-inventory: generated by `python3 .scripts/check-module-graph.py --write-doc`; do not edit -->"
DOC_END = "<!-- /module-graph-inventory -->"
SEMVER = re.compile(r"v(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)"
                    r"(?:-([0-9A-Za-z-]+(?:\.[0-9A-Za-z-]+)*))?(?:\+[0-9A-Za-z.-]+)?")


class SetupError(Exception):
    """The check could not run; never reported as a pass."""


def semver_key(version):
    """Semantic Version 2.0 precedence; pseudo-versions are prereleases."""
    match = SEMVER.fullmatch(version)
    if not match:
        raise ValueError(f"not a canonical semantic version: {version}")
    major, minor, patch, pre = match.groups()
    core = (int(major), int(minor), int(patch))
    if pre is None:
        return core + ((1,),)
    parts = tuple((0, int(p), "") if p.isdigit() else (1, 0, p) for p in pre.split("."))
    return core + ((0, parts),)


def internal(path):
    return path == REPO_MODULE or path.startswith(REPO_MODULE + "/")


def manifests(root):
    proc = subprocess.run(["git", "-C", str(root), "ls-files", "-z", "--cached", "--others",
                           "--exclude-standard"], capture_output=True, text=True)
    if proc.returncode:
        raise SetupError(f"git ls-files failed in {root}: {proc.stderr.strip()}")
    found = sorted(p for p in proc.stdout.split("\0") if p and Path(p).name == "go.mod")
    if not found:
        raise SetupError(f"no go.mod files found under {root}")
    return found


def parse(go, root, relative):
    env = dict(os.environ, GOTOOLCHAIN="local", GOWORK="off", GOFLAGS="")
    proc = subprocess.run([go, "mod", "edit", "-json", str(root / relative)],
                          capture_output=True, text=True, env=env)
    if proc.returncode:
        return None, proc.stderr.strip()
    return json.loads(proc.stdout), None


def inventory(root, snapshot_path, go):
    snapshot = json.loads(snapshot_path.read_text())
    floors = snapshot["modules"]
    # Pseudo-versions end in [.-]TIMESTAMP-COMMIT12 (vX.0.0-T-C or vX.Y.Z-0.T-C).
    stamp = f"{snapshot['snapshot_time']}-{snapshot['snapshot_commit'][:12]}"
    violations, rows, edges, modules = [], [], [], {}
    for path, floor in sorted(floors.items()):
        if not SEMVER.fullmatch(floor) or not re.search(r"[.-]" + re.escape(stamp) + "$", floor):
            violations.append(f"snapshot: {path} floor {floor} is not a pseudo-version of snapshot {stamp}")
    parsed = {}
    for relative in manifests(root):
        data, error = parse(go, root, relative)
        if data is None:
            violations.append(f"{relative}: go mod edit -json failed: {error}")
            continue
        parsed[relative] = data
        module = data["Module"]["Path"]
        if not internal(module):
            violations.append(f"{relative}: module {module} is outside {REPO_MODULE}")
        if module in modules:
            violations.append(f"{relative}: module {module} also declared by {modules[module]}")
        modules[module] = relative
    for path in sorted(set(floors) - set(modules)):
        violations.append(f"snapshot: {path} has a floor but no go.mod in this checkout")
    for relative, data in parsed.items():
        count = current = 0
        targets = [(r["Path"], r["Version"], "require") for r in data.get("Require") or []]
        # A versioned internal replacement would select a version too.
        targets += [(r["New"]["Path"], r["New"]["Version"], "replace")
                    for r in data.get("Replace") or [] if r["New"].get("Version")]
        for path, version, kind in targets:
            if not internal(path):
                continue
            if kind == "require":
                count += 1
                edges.append({"manifest": relative, "path": path, "version": version})
            floor = floors.get(path)
            if path not in modules:
                violations.append(f"{relative}: {kind} {path} {version}: no such module in this checkout")
            elif floor is None:
                violations.append(f"{relative}: {kind} {path} {version}: no snapshot floor recorded")
            else:
                try:
                    stale = semver_key(version) < semver_key(floor)
                except ValueError as error:
                    violations.append(f"{relative}: {kind} {path}: {error}")
                    continue
                if stale:
                    violations.append(f"{relative}: {kind} {path} {version} is older than snapshot {floor}")
                elif kind == "require":
                    current += 1
        rows.append((relative, count, current))
    return {"manifests": rows, "edges": edges, "violations": violations,
            "total": sum(r[1] for r in rows), "consumers": sum(1 for r in rows if r[1])}


def render(result):
    # Edge counts only: version currency is enforced by the floor check itself.
    lines = [DOC_BEGIN, "| Consumer manifest | Internal require edges |", "| --- | ---: |"]
    lines += [f"| `{name}` | {count} |" for name, count, _ in result["manifests"]]
    lines.append(f"| **Total: {len(result['manifests'])} manifests / {result['consumers']} consumers** "
                 f"| **{result['total']}** |")
    lines.append(DOC_END)
    return "\n".join(lines)


def check_doc(doc, result, write):
    text = doc.read_text()
    start, end = text.find(DOC_BEGIN), text.find(DOC_END)
    if start < 0 or end < start:
        return [f"{doc.name}: generated inventory markers missing"]
    updated = text[:start] + render(result) + text[end + len(DOC_END):]
    if write:
        doc.write_text(updated)
        text = updated
    problems = [] if updated == text else [f"{doc.name}: inventory table is stale; rerun with --write-doc"]
    # Prose counts outside the table must agree with the computed inventory.
    for claim in re.findall(r"(\d+) internal require edges", text):
        if int(claim) != result["total"]:
            problems.append(f"{doc.name}: claims {claim} internal require edges; inventory has {result['total']}")
    for claim in re.findall(r"(\d+) `go\.mod` files", text):
        if int(claim) != len(result["manifests"]):
            problems.append(f"{doc.name}: claims {claim} go.mod files; inventory has {len(result['manifests'])}")
    return problems


def main():
    default_root = Path(__file__).resolve().parents[1]
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--root", type=Path, default=default_root)
    parser.add_argument("--snapshot", type=Path, help="default: ROOT/experiments/module-graph-snapshot.json")
    parser.add_argument("--doc", type=Path, help="default: ROOT/experiments/MODULE-GRAPH.md")
    parser.add_argument("--write-doc", action="store_true", help="regenerate the inventory table")
    parser.add_argument("--json", type=Path, help="write the full inventory as JSON evidence")
    parser.add_argument("--go", default=os.environ.get("GO") or shutil.which("go"))
    args = parser.parse_args()
    root = args.root.resolve()
    try:
        if not args.go:
            raise SetupError("go is unavailable")
        result = inventory(root, args.snapshot or root / "experiments/module-graph-snapshot.json", args.go)
        doc = args.doc or root / "experiments/MODULE-GRAPH.md"
        result["violations"] += check_doc(doc, result, args.write_doc)
    except (SetupError, OSError, KeyError, json.JSONDecodeError) as error:
        print(f"module graph check could not run: {error}", file=sys.stderr)
        return 2
    for name, count, current in result["manifests"]:
        print(f"{name}: {count} internal require edges, {current} at or above snapshot")
    print(f"total: {len(result['manifests'])} manifests, {result['consumers']} consumers, "
          f"{result['total']} internal require edges, {len(result['violations'])} violations")
    if args.json:
        args.json.write_text(json.dumps(result, indent=2) + "\n")
    for violation in result["violations"]:
        print(f"VIOLATION {violation}")
    return 1 if result["violations"] else 0


if __name__ == "__main__":
    sys.exit(main())
